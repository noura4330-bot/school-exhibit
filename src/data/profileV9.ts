export function applyProfileV9(ini: Partial<InitiativeProfile>) {
  for (const [k, old] of Object.entries(previous) as [keyof InitiativeProfile, string][]) {
    const cur = ini[k]
    if (typeof cur === 'string' && cur.trim() === old) (ini as Record<string, unknown>)[k] = initiativeProfileDefaults[k as keyof typeof initiativeProfileDefaults]
  }
  if (typeof ini.domain !== 'string' || !ini.domain.trim()) ini.domain = INITIATIVE_DOMAIN
}
