const PG_NOTE =
  'التقييم الأولي لعناصر الحوكمة مسجل في صفحة السياسات والحوكمة. لا يُحدد المستوى قبل إدخال مؤشرات المقياس الرسمي ومراجعة الشواهد.'

const blank = (v: unknown) => typeof v !== 'string' || !v.trim()

/** يملأ بيانات التخطيط في الخانات الفارغة فقط، ولا يغيّر أي قيمة أدخلتها المستخدمة */
export function applyPlanning(d: AppData): AppData {
  const now = nowIso()
  const base = () => ({ id: newId(), createdAt: now, updatedAt: now })
  const ini = { ...d.initiative }
  for (const k of ['rationale', 'problem', 'baseline', 'target', 'measurementPlan'] as const)
    if (blank(ini[k])) ini[k] = planningInitiative[k]
  if (blank(ini.kpis) || ini.kpis.trim() === previousKpis) ini.kpis = planningInitiative.kpis

  const policies = d.policies.map((p) => {
    const f = policyFills[p.element.trim()]
    if (!f) return p
    const untouched = p.status === 'not_started' && blank(p.docName) && blank(p.summary)
    const next = { ...p }
    if (untouched) {
      Object.assign(next, { docName: f.docName, summary: f.summary, status: f.status, reviewNotes: f.reviewNotes })
      if (f.status !== 'not_started' && blank(next.createdOn)) next.createdOn = now.slice(0, 10)
    }
    if (blank(next.owner)) next.owner = f.owner
    if (blank(next.nextAction)) next.nextAction = f.nextAction
    if (untouched && !next.assessment) {
      next.assessment = f.assessment
      if (blank(next.assessmentNote)) next.assessmentNote = f.assessmentNote
    }
    return JSON.stringify(next) !== JSON.stringify(p) ? { ...next, updatedAt: now } : p
  })

  const haveMeasure = new Set(d.impact.map((m) => m.title.trim()))
  const impact = [
    ...d.impact,
    ...plannedMeasures
      .filter((m) => !haveMeasure.has(m.title))
      .map((m) => ({ ...base(), ...m, baseline: '', actual: '', measuredOn: '', causalDesign: false })),
  ]

  const haveTask = new Set(d.tasks.map((t) => t.title.trim()))
  const tasks = [
    ...d.tasks.map((t) => {
      const p = taskProgress[t.title.trim()]
      if (!p || t.status !== 'not_started') return t
      if (p.status === 'done' && (blank(ini.rationale) || blank(ini.problem))) return t
      return { ...t, status: p.status, notes: t.notes?.trim() ? `${t.notes.trim()} ${p.note}` : p.note, updatedAt: now }
    }),
    ...planningTasks.filter((t) => !haveTask.has(t.title)).map((t) => ({ ...base(), ...t, due: '', status: 'not_started' as const })),
  ]

  const areas = d.areas.map((a) =>
    a.isPolicyGovernance && !a.notes.includes(PG_NOTE) ? { ...a, notes: a.notes.trim() ? `${a.notes.trim()}\n${PG_NOTE}` : PG_NOTE } : a,
  )

  return { ...d, initiative: ini, policies, impact, tasks, areas }
}
