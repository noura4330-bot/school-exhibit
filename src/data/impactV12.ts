const untouched = (m: ImpactMeasure) => ![m.baseline, m.target, m.actual, m.measuredOn].some((x) => x?.trim())

/** يضيف المؤشرات الستة مرة واحدة. يستبدل المؤشر التخطيطي المماثل فقط إن لم تُدخل فيه قيم، ولا يمس غيره */
export function applyImpactV12(d: AppData): AppData {
  const now = nowIso()
  const have = new Set(d.impact.map((m) => m.title.trim()))
  let impact = [...d.impact]
  for (const { replaces, ...m } of userMeasures) {
    if (have.has(m.title)) continue
    const i = replaces ? impact.findIndex((x) => x.title.trim() === replaces && untouched(x)) : -1
    if (i >= 0) impact[i] = { ...impact[i], ...m, actual: '', measuredOn: '', updatedAt: now }
    else impact = [...impact, { id: newId(), createdAt: now, updatedAt: now, ...m, actual: '', measuredOn: '', causalDesign: false }]
    have.add(m.title)
  }
  return { ...d, impact }
}
