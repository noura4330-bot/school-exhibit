/** النتيجة دون النسبة المكتوبة يدويًا، و110 طالبات لـ OneNote */
const actualFor = (programId: string, old: string) =>
  programId === 'onenote' ? '110 طالبات' : old.replace(/\s*\([\d.]+%\)\s*$/, '')

export function applyMeasuresV19(list: ProgramMeasure[]): ProgramMeasure[] {
  return list.map((m) => {
    const row = v18Rows.find(([p, t]) => p === m.programId && t === m.title.trim())
    if (!row) return m
    const [, , , oldActual, oldNotes] = row
    const next = { ...m }
    if (m.actual.trim() === oldActual) next.actual = actualFor(m.programId, oldActual)
    if (m.notes.trim() === oldNotes && notes[m.programId]) next.notes = notes[m.programId]
    return next.actual === m.actual && next.notes === m.notes ? m : { ...next, updatedAt: new Date().toISOString() }
  })
}
